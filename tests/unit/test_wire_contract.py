"""Pin every parser against ocx's own published report contract.

`tests/fixtures/contract/reports.v1.json` is generated by ocx from the very
Rust types its CLI serializes (`cargo run -p ocx_schema -- reports`), so it is
evidence about the wire. The rest of this suite parses hand-written payloads,
which are evidence about whoever typed them — that is how three presence-rule
inversions reached `main` and one of them crashed `env()`.

Two failure classes are asserted, both of which end in a `KeyError` or a
silently empty struct at run time:

* **phantom** — the parser reads a key ocx never publishes, so it can only ever
  see `None` (or raise).
* **unsafe** — the parser `_need`s a key ocx may omit, so an ordinary run
  raises instead of returning a value.

A third, **lossy** — reading with `.get` a key ocx always writes — cannot break
a parse, so it is recorded in `_WAIVED` rather than fixed blind.
"""

